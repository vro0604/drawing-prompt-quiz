--
--   display_name / bio / links は 001 が配った列権限で直接更新できるので、
--   関数が無くても変更手段は残る（ただし画面はこの関数を呼んでいるため、
--   /account のフォームは動かなくなる）。
--
-- ============================================================================


begin;

drop function if exists public.update_my_profile(text, text, text, jsonb);

commit;


