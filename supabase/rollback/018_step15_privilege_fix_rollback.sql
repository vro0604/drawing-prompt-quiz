-- --- 1. 今後作る表の既定を元に戻す -------------------------------------------
--
-- Supabase の初期状態（新しい表に ALL が自動で付く）に戻る。
-- **書き忘れると権限が付く**構造に戻るということ。

alter default privileges in schema public
  grant all on tables to anon, authenticated;


-- --- 2. handle_history の権限を戻す -------------------------------------------
--
-- ここは「戻す」というより、Supabase の既定と同じ状態を作り直す。

grant all on public.handle_history to anon, authenticated;


-- --- 3. profiles の保護列 ------------------------------------------------------
--
-- **戻さない。**
--
-- 第2節の revoke は、もともと付いていない権限を落としただけで、
-- 何も変えていない（001 は6列にしか UPDATE を配っていない）。
-- 戻す＝新たに配ることになり、それは 001 の設計を変えてしまう。
--
