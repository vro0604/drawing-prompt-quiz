-- ============================================================================
-- 001_profiles_rollback.sql ／ 001_profiles.sql を取り消す
-- ============================================================================
--
-- 【使うとき】
--   Step 2 のデータベース側の変更をやり直したい／Step 1 の状態に戻したいとき。
--
-- 【実行方法】
--   Supabase ダッシュボード → SQL Editor → New query
--   → この中身を貼り付けて Run
--
-- 【消えるもの】
--   ・profiles テーブルと、その中の全データ
--   ・profiles を自動生成するトリガーと関数
--   ・匿名状態を同期するトリガーと関数
--   ・開発途中に作った補助関数（残っていれば）
--
-- 【消えないもの】
--   ・すでに発行されたユーザー（auth.users の行）は残る。
--     消したい場合は、この SQL のあと
--     ダッシュボード → Authentication → Users から個別に削除する。
--
-- 実行順は 001_profiles.sql の逆。使っている側から先に外す。
-- トリガー → 関数 → テーブル の順。逆にすると
-- 「まだ使われている」と言われて消せない。
--
-- if exists を付けてあるので、対象が無くてもエラーにならない。
-- 途中まで実行した状態から流しても問題ない。
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1. auth.users に付けたトリガーを外す
-- ----------------------------------------------------------------------------

-- ユーザー作成時に profiles を作るトリガー
drop trigger if exists on_auth_user_created on auth.users;

-- 匿名 → 正式登録の変化を profiles に反映するトリガー
drop trigger if exists on_auth_user_anonymous_changed on auth.users;


-- ----------------------------------------------------------------------------
-- 2. トリガーが呼んでいた関数を消す
-- ----------------------------------------------------------------------------

drop function if exists public.handle_new_user();
drop function if exists public.sync_profile_anonymous_flag();


-- ----------------------------------------------------------------------------
-- 3. テーブルを消す
-- ----------------------------------------------------------------------------
--
-- 中身も一緒に消える。RLS ポリシーと列単位の権限もテーブルに付属するので
-- 個別に消す必要はない。実行前に本当に良いか確認すること。

drop table if exists public.profiles;


-- ----------------------------------------------------------------------------
-- 4. 開発途中に作って、その後やめた補助関数を消す
-- ----------------------------------------------------------------------------
--
-- is_falsely_public は、クライアントが is_anonymous を書き換えられる前提の
-- 検査用関数だった。その経路自体を塞いだため、現行の 001_profiles.sql には
-- 含まれていない。初期の版を実行した環境にだけ残っている可能性があるので、
-- 念のためここで落とす。一度も作っていなければ何も起きない。
--
-- テーブルより後に消すのは、ポリシーから参照されていると消せないため。

drop function if exists public.is_falsely_public(boolean);


