-- 読みの入っていない語が残っていないことを、当てた場でも確かめる。
-- **入れ忘れた語は判定をすり抜ける**ので、静かに通さない。
do $$
declare
  v_tags int;
  v_vocab int;
begin
  select count(*) into v_tags  from public.tags where reading is null;
  select count(*) into v_vocab from public.flavor_vocab where reading is null;

  if v_tags > 0 or v_vocab > 0 then
    raise exception
      '読みの入っていない語がある（お題語 %件 / ヒント語 %件）。'
      '語彙を足したときは、この migration の対応表にも足すこと。', v_tags, v_vocab;
  end if;
end $$;


-- ----------------------------------------------------------------------------
-- 判定を1本にまとめる
-- ----------------------------------------------------------------------------
--
-- 返す値（使えないときの理由）
--   exact       表記をそろえると同じ語
--   substring   どちらかがどちらかを文字として含む（正解語を含む複合語もここ）
--   reading     読みが同じ（漢字とかなの言い換え。「馬」と「うま」）
--   kanji       漢字を1文字でも共有する（「古い」と「古書」のような語幹の重なり）
--   synonym     同じ同義グループ
--   manual      人が1件ずつ登録した禁止の組
--   null        使える
--
-- 【読みは「同じ」だけを見る。「含む」は見ない】
--   含むところまで広げると、かなの並びが偶然重なるだけの組を拾う。
--   いまの語彙で実際に数えたら9組が当たり、**9組とも漏洩ではなかった**
--   （「匂い（におい）」と「老い（おい）」、「帰る（かえる）」と「抱える（かかえる）」など。
--   scripts/vocab-audit.mjs で数えた）。日本語は語の切れ目が字に出ないので、
--   かなの部分一致は意味の近さの証拠にならない。

-- 【漢字の共有まで止める理由】
--   「古書」が答えのときに「古い」をヒントに出せると、4択の中では
--   ほぼ答えを指す。文字列としては互いに含まれないので、上の substring では
--   拾えない。同じ漢字を含むかどうかで止める。
--   広く止めることになるが、実測で1語あたり使えるヒント語は 90語中 88語前後、
--   4語のお題でも 85語前後が残る（同じく vocab-audit.mjs で数えた）。

create or replace function public.flavor_block_reason(
  p_vocab_id bigint,
  p_tag_id   bigint
)
returns text
language sql
stable
security definer
set search_path = ''
as $fn$
  select case
    when v.label is null or t.label is null then null

    when public.flavor_normalize(v.label) = public.flavor_normalize(t.label)
      then 'exact'

    when position(t.label in v.label) > 0
      or position(v.label in t.label) > 0
      or position(public.flavor_normalize(t.label) in public.flavor_normalize(v.label)) > 0
      or position(public.flavor_normalize(v.label) in public.flavor_normalize(t.label)) > 0
      then 'substring'

    -- 読みが同じ（漢字とかなの言い換え。「馬」と「うま」）
    when v.reading is not null and t.reading is not null
     and public.flavor_normalize(v.reading) = public.flavor_normalize(t.reading)
      then 'reading'

    -- 漢字を1文字でも共有する。
    -- 「古い」と「古書」のように、文字列としては含まれないのに
    -- 語幹が重なる組を止める。
    when exists (
      select 1
        from regexp_split_to_table(v.label, '') c
       where c ~ '[一-鿿]'
         and position(c in t.label) > 0
    ) then 'kanji'

    when v.synonym_group is not null and t.synonym_group is not null
     and v.synonym_group = t.synonym_group
      then 'synonym'

    when exists (
      select 1 from public.flavor_vocab_blocks b
       where b.vocab_id = p_vocab_id and b.tag_id = p_tag_id
    ) then 'manual'

    else null
  end
  from (select label, reading, synonym_group from public.flavor_vocab where id = p_vocab_id) v
  full outer join (select label, reading, synonym_group from public.tags where id = p_tag_id) t
    on true;
$fn$;

comment on function public.flavor_block_reason(bigint, bigint) is
  'そのヒント語を、その正解語のお題で使えない理由を1語で返す（使えるなら null）。'
  '候補の提示・保存・検査の3つが、この1本だけを見る。';

revoke all on function public.flavor_block_reason(bigint, bigint)
  from public, anon, authenticated;


create or replace function public.flavor_vocab_is_allowed(
  p_vocab_id  bigint,
  p_prompt_id uuid
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $fn$
  select
    exists (
      select 1 from public.flavor_vocab v
       where v.id = p_vocab_id
         and v.is_active
         -- 目で確認していない語は使えない
         and v.is_reviewed
    )
    and not exists (
      select 1
        from public.prompt_cards pc
       where pc.prompt_id = p_prompt_id
         and public.flavor_block_reason(p_vocab_id, pc.tag_id) is not null
    );
$fn$;

comment on function public.flavor_vocab_is_allowed(bigint, uuid) is
  '回答前のフレーバーに、その語をそのお題で使ってよいか（D162 の①〜④ ＋ 読み）。'
  '判定そのものは flavor_block_reason が持つ。内部専用。';

revoke all on function public.flavor_vocab_is_allowed(bigint, uuid)
  from public, anon, authenticated;
