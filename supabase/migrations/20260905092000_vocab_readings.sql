-- ============================================================================
-- vocab_readings ／ 漢字とかなの対応を入れ、ヒント語の漏れ判定に足す
-- ============================================================================
--
-- 【何が足りなかったか】
--   フレーバー（ヒント）の語がお題の正解を漏らしていないかは、いままで
--     ① 文字がそのまま重なる  ② 表記をそろえてから重なる（カタカナ⇔ひらがな）
--     ③ 同義グループが同じ    ④ 人が1件ずつ登録した禁止の組
--   の4つで見ていた。**漢字とかなの書き換えは、どれでも拾えない。**
--   20260904095000 のコメント自身が「できない」と書いている
--   （「馬」と「うま」は別物として通る）。
--
--   拾えないまま「候補の絞り込みが動く」ことを合格の根拠にしていたので、
--   ここで対応表そのものを入れる。
--
-- 【入れるもの】
--   tags.reading         お題語 348語の読み（ひらがな）
--   flavor_vocab.reading ヒント語 90語の読み
--
--   数はどちらも全件。**一部だけ入れて「対応した」としない。**
--   （2026-09-05 時点の全語彙を数えて 348 と 90。db から数えて突き合わせた）
--
-- 【読みを誰が書いたか】
--   私（Claude）が1語ずつ書いた。**ユーザーの承認は受けていない。**
--   読みが違えば、その語だけ判定がすり抜ける。承認の対象。
--
-- 【判定を1本にまとめる】
--   flavor_block_reason(vocab, tag) が「なぜ使えないか」を1語で返す。
--   使えるなら null。flavor_vocab_is_allowed はこの関数を呼ぶだけにする。
--   **検査（scripts/vocab-audit.mjs）も同じ関数を呼ぶ。**
--   判定を試験側へ書き写すと、規則を直したときに試験だけ古いまま通る。
--
-- ============================================================================


alter table public.tags         add column if not exists reading text;
alter table public.flavor_vocab add column if not exists reading text;

comment on column public.tags.reading is
  'ひらがなの読み（2026-09-05）。漢字とかなの言い換えを見つけるために使う。'
  '私が1語ずつ書いた値で、ユーザーの承認は受けていない。';
comment on column public.flavor_vocab.reading is
  'ひらがなの読み（2026-09-05）。tags.reading と突き合わせる。';


