/**
 * 回答の知らせ（D192）。
 *
 * 【これは何か】
 *   自分の作品に回答が来ていて、その結果をまだ開いていない状態のこと。
 *   「知らせ」の実体は表ではない。作品ごとに持っている
 *   「最後に結果を開いた時刻」と、回答が来た時刻の差である。
 *
 * 【数を持っていない理由】
 *   この型にも、これを返す DB の関数にも、件数が1つも無い。
 *   出所: ユーザー指示（2026-09-10）「絶対に表示しない：回答件数 /
 *   通知件数 / 数字badge / 未読を示す丸badge / いいね型カウンター」。
 *   画面で消すのではなく、**数そのものを運ばない。**
 *   運んでいなければ、あとから画面の都合で出てしまう道が無い。
 *
 * 【回答者を持っていない理由】
 *   出所: ユーザー指示（2026-09-10）「回答者ID・名前を通知へ出さない。
 *   通知API/RPCにも不要な回答者情報を返さない。」
 *   この型は作品の情報しか持たない。
 */

/** 未確認の回答がある自分の作品1件。回答の件数も回答者も含まない */
export type UnseenResultWork = {
  work_id: string;
  title: string;
  image_path: string;
  image_width: number;
  image_height: number;
  division: string;
  /**
   * その作品に、まだ開いていない回答のうち最も新しいものが来た時刻。
   * 並べ替えにだけ使う。画面には出さない
   * （時刻から回答が来た頻度が読めてしまうため）。
   */
  latest_answer_at: string;
};

/** 一覧で一度に受け取る上限。DB 側も 100 で頭打ちにしている */
export const UNSEEN_LIST_LIMIT = 50;
